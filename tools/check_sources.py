#!/usr/bin/env python3
"""Механическая проверка реестра источников docs/reference/sources.md.

Проверяет то, что ворота `sdd.py проверить` не смотрят: форму строк реестра,
порядок номеров и имена файлов в разделе снимков экранов, наличие самих
снимков, посторонние адреса почты и ссылки на несуществующие SRC в
docs/reference/ui-patterns.md.

Снимки лежат вне репозитория (по умолчанию <корень>/../bitrix-demo/screens);
если каталога нет, проверка файлов пропускается с пометкой «ПРОПУСК», а код
возврата остаётся нулевым. Содержимое снимков не читается — только имена.

    python3 tools/check_sources.py [--корень КАТАЛОГ] [--снимки КАТАЛОГ]

Каждая находка — строка «файл:строка: причина»; код 1 при находках, иначе 0.
"""
import argparse
import re
import sys
from pathlib import Path

_ТУТ = Path(__file__).resolve().parent
if str(_ТУТ) not in sys.path:
    sys.path.insert(0, str(_ТУТ))

from sdd import (  # noqa: E402  (переиспользуем, не дублируем)
    КОДОВАЯ_ВСТАВКА_РЕ,
    СС_НА_ИСТОЧНИК_РЕ,
    собрать_реестр_источников,
)

КОРЕНЬ = _ТУТ.parent
РЕЕСТР = "docs/reference/sources.md"
ПАТТЕРНЫ_UI = "docs/reference/ui-patterns.md"
РАЗДЕЛ_СНИМКОВ = "Снимки экранов тестового портала"
ПЕРВЫЙ_НОМЕР_СНИМКА = 401
ЯЧЕЕК = 6

КОД_РЕ = re.compile(r"^SRC-(\d+)$")
ДАТА_РЕ = re.compile(r"^\d{4}-\d{2}-\d{2}$")
ГДЕ_СНИМОК_РЕ = re.compile(r"^bitrix-demo/screens/(\d{3})-([A-Za-z0-9-]+)\.png \((.+)\)$")
ИМЯ_PNG_РЕ = re.compile(r"screens/([^\s()]+\.png)")
# \w, а не A-Za-z: адрес на кириллическом домене (…@почта.рф) тоже находка.
ПОЧТА_РЕ = re.compile(r"[\w.%+-]+@([\w-]+(?:\.[\w-]+)+)")
# Строка таблицы, где первая ячейка — код источника; пробелы как в sdd.py.
СТРОКА_SRC_РЕ = re.compile(r"^\s*\|\s*SRC-")
ГРАНИЦА_ЯЧЕЕК_РЕ = re.compile(r"(?<!\\)\|")


def разобрать_ячейки(строка: str) -> list:
    """Ячейки строки таблицы без внешних «|» и пробелов по краям."""
    тело = строка.strip()
    if тело.startswith("|"):
        тело = тело[1:]
    if тело.endswith("|") and not тело.endswith("\\|"):
        тело = тело[:-1]
    return [ячейка.strip() for ячейка in ГРАНИЦА_ЯЧЕЕК_РЕ.split(тело)]


def проверить_реестр(текст: str, файл: str = РЕЕСТР):
    """(находки, строки_снимков). Строки снимков: (номер_строки, номер_SRC, где)."""
    находки = []
    увиденные = {}
    снимки = []
    раздел = ""
    предыдущий = None
    for номер, строка in enumerate(текст.split("\n"), 1):
        if строка.startswith("## "):
            раздел = строка[3:].strip()
            continue
        if not СТРОКА_SRC_РЕ.match(строка):
            continue
        ячейки = разобрать_ячейки(строка)
        if len(ячейки) != ЯЧЕЕК:
            находки.append(f"{файл}:{номер}: в строке реестра {len(ячейки)} ячеек, нужно {ЯЧЕЕК}")
            continue
        код, что, где, про, дата, фраза = ячейки
        совпадение = КОД_РЕ.match(код)
        if not совпадение:
            находки.append(f"{файл}:{номер}: код источника не вида SRC-<цифры>")
            continue
        число = int(совпадение.group(1))
        if код in увиденные:
            находки.append(f"{файл}:{номер}: код {код} повторяется (первый раз в строке {увиденные[код]})")
        else:
            увиденные[код] = номер
        if not ДАТА_РЕ.match(дата):
            находки.append(f"{файл}:{номер}: {код}: дата не вида ГГГГ-ММ-ДД")
        for имя, значение in (("Что это", что), ("Где", где), ("Опорная фраза", фраза)):
            if not значение:
                находки.append(f"{файл}:{номер}: {код}: пустая ячейка «{имя}»")
        if раздел != РАЗДЕЛ_СНИМКОВ:
            continue
        ожидаемый = ПЕРВЫЙ_НОМЕР_СНИМКА if предыдущий is None else предыдущий + 1
        if число != ожидаемый:
            находки.append(
                f"{файл}:{номер}: {код}: номер снимка не подряд, ожидался SRC-{ожидаемый}"
            )
        предыдущий = число
        снимок = ГДЕ_СНИМОК_РЕ.match(где)
        имя_файла = None
        if где and not снимок:
            находки.append(
                f"{файл}:{номер}: {код}: «Где» не вида bitrix-demo/screens/NNN-имя.png (адрес)"
            )
            найден = ИМЯ_PNG_РЕ.search(где)
            if найден:
                имя_файла = найден.group(1)
        elif снимок:
            nnn = int(снимок.group(1))
            if nnn != число - 400:
                находки.append(
                    f"{файл}:{номер}: {код}: номер в имени файла {снимок.group(1)} не равен {число - 400:03d}"
                )
            имя_файла = f"{снимок.group(1)}-{снимок.group(2)}.png"
        if not (про == "коробка" or про.startswith("коробка,") or про.startswith("коробка ")):
            находки.append(f"{файл}:{номер}: {код}: «Про что» должно начинаться со слова «коробка»")
        снимки.append((номер, код, имя_файла))
    return находки, снимки


def проверить_файлы_снимков(снимки: list, каталог: Path, файл: str = РЕЕСТР):
    """(находки, пропуски) по каталогу снимков."""
    if not каталог.is_dir():
        return [], [f"ПРОПУСК: каталог снимков не найден: {каталог}; проверка файлов не выполнена"]
    находки = []
    упомянуты = {}
    for номер, код, имя in снимки:
        if имя is None:
            continue
        if имя in упомянуты:
            находки.append(
                f"{файл}:{номер}: {код}: файл {имя} уже упомянут в строке {упомянуты[имя]}"
            )
        else:
            упомянуты[имя] = номер
        if not (каталог / имя).is_file():
            находки.append(f"{файл}:{номер}: {код}: файл снимка {имя} не найден в каталоге снимков")
    for путь in sorted(каталог.glob("*.png")):
        if путь.name not in упомянуты:
            находки.append(f"{файл}:0: файл {путь.name} лежит в каталоге снимков, но не описан в реестре")
    return находки, []


def проверить_почту(текст: str, файл: str) -> list:
    находки = []
    for номер, строка in enumerate(текст.split("\n"), 1):
        for совпадение in ПОЧТА_РЕ.finditer(строка):
            домен = совпадение.group(1).lower()
            if домен != "example.com" and not домен.endswith(".example.com"):
                находки.append(f"{файл}:{номер}: адрес почты не на example.com")
    return находки


def проверить_ссылки_ui(текст: str, реестр: set, файл: str = ПАТТЕРНЫ_UI) -> list:
    находки = []
    for номер, строка in enumerate(текст.split("\n"), 1):
        очищенная = КОДОВАЯ_ВСТАВКА_РЕ.sub(lambda м: " " * len(м.group(0)), строка)
        for совпадение in СС_НА_ИСТОЧНИК_РЕ.finditer(очищенная):
            if совпадение.group(0) not in реестр:
                находки.append(f"{файл}:{номер}: {совпадение.group(0)} нет в реестре источников")
    return находки


def проверить(корень: Path, каталог_снимков: Path = None):
    """(находки, пропуски) по всему репозиторию."""
    if каталог_снимков is None:
        каталог_снимков = корень.parent / "bitrix-demo" / "screens"
    находки, пропуски = [], []
    путь_реестра = корень / РЕЕСТР
    if not путь_реестра.is_file():
        return [f"{РЕЕСТР}:0: файл реестра не найден"], []
    текст_реестра = путь_реестра.read_text(encoding="utf-8")
    н, снимки = проверить_реестр(текст_реестра)
    находки += н
    н, п = проверить_файлы_снимков(снимки, каталог_снимков)
    находки += н
    пропуски += п
    находки += проверить_почту(текст_реестра, РЕЕСТР)
    путь_ui = корень / ПАТТЕРНЫ_UI
    if путь_ui.is_file():
        текст_ui = путь_ui.read_text(encoding="utf-8")
        находки += проверить_почту(текст_ui, ПАТТЕРНЫ_UI)
        находки += проверить_ссылки_ui(текст_ui, собрать_реестр_источников(корень))
    return находки, пропуски


def main(арг: list) -> int:
    разбор = argparse.ArgumentParser(description="Проверка реестра источников и снимков экранов")
    разбор.add_argument("--корень", default=str(КОРЕНЬ), help="корень репозитория")
    разбор.add_argument("--снимки", default=None, help="каталог снимков экранов")
    параметры = разбор.parse_args(арг)
    корень = Path(параметры.корень)
    каталог = Path(параметры.снимки) if параметры.снимки else None
    находки, пропуски = проверить(корень, каталог)
    for п in пропуски:
        print(п)
    for н in находки:
        print(н)
    if находки:
        print(f"реестр источников: находок {len(находки)}")
        return 1
    print("реестр источников: находок нет")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
