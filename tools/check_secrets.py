#!/usr/bin/env python3
"""Не пускает секреты в git — pre-commit сканер индекса.

Проверка общая, без привязки к какому-то одному источнику секрета: буквальный
`SECRET_KEY`, пароль в DSN `postgres://…`, пароль/токен/ключ, заданный
литералом в кавычках, токен Telegram-бота, приватный ключ в формате PEM.
Заглушки (`***`, `${VAR}`, чтение из окружения через `os.environ`/`env(`/
`getenv(`, `changeme`, `example`, пустое значение) секретами не считаются —
иначе сканер отказывал бы на собственных примерах в документации.

Файлы `.env` (и любой `*.env`, кроме `.env.example`) в коммит не пускаются
вовсе, независимо от содержимого: это личные настройки разработчика, а не
код проекта.

Значения секретов скрипт никогда не печатает — только файл, строку и причину.

    python3 tools/check_secrets.py   # индекс; код 1 — нашёл проблему
"""
import re
import subprocess
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent

# Значения-заглушки — не секреты, а места для будущего секрета или пример.
_ЗАГЛУШКИ = ("changeme", "example")


def похоже_на_заглушку(значение: str) -> bool:
    очищенное = (значение or "").strip()
    if not очищенное:
        return True  # пустое значение
    if "***" in очищенное or "${" in очищенное:
        return True
    # Выражение шаблона Django подставляется при отрисовке, а не хранится:
    # hx-headers='{"X-CSRFToken": "{{ csrf_token }}"}' есть почти в каждом шаблоне HTMX.
    if "{{" in очищенное or "{%" in очищенное:
        return True
    нижний = очищенное.lower()
    return any(заглушка in нижний for заглушка in _ЗАГЛУШКИ)


# Строка читает секрет из окружения, а не хранит его — не наша забота.
ЧТЕНИЕ_ИЗ_ОКРУЖЕНИЯ_РЕ = re.compile(r"os\.environ|\benv\(|\bgetenv\(")

_ИДЕНТ = r"[A-Za-z0-9_]*"


def _литерал_ре(ключевое_слово: str, мин_длина: int) -> re.Pattern:
    """Присваивание «…ключевое_слово… = "литерал (>= мин_длина символов)"»."""
    return re.compile(
        rf"\b({_ИДЕНТ}{ключевое_слово}{_ИДЕНТ})[\"']?\s*[:=]\s*[\"']([^\"']{{{мин_длина},}})[\"']",
        re.IGNORECASE,
    )


# (причина, регулярка, номер_группы_со_значением)
ШАБЛОНЫ_ПРИСВАИВАНИЯ = [
    ("SECRET_KEY литералом", _литерал_ре("SECRET_KEY", 1), 2),
    (
        "пароль/токен/ключ литералом",
        _литерал_ре("(?:password|passwd|pwd|secret|token|api_key)", 8),
        2,
    ),
]

DSN_POSTGRES_РЕ = re.compile(r"postgres(?:ql)?://[^:@/\s'\"]+:([^@/\s'\"]+)@")
ТОКЕН_TELEGRAM_РЕ = re.compile(r"\b\d{8,10}:[A-Za-z0-9_-]{35}\b")
ПРИВАТНЫЙ_КЛЮЧ_РЕ = re.compile(r"-----BEGIN [A-Z0-9 ]*PRIVATE KEY-----")


def проверить_строку(строка: str) -> list:
    """Список причин находок секретов в одной строке текста (без имени/номера)."""
    if ЧТЕНИЕ_ИЗ_ОКРУЖЕНИЯ_РЕ.search(строка):
        return []
    находки = []
    for причина, регулярка, номер_группы in ШАБЛОНЫ_ПРИСВАИВАНИЯ:
        совпадение = регулярка.search(строка)
        if совпадение and not похоже_на_заглушку(совпадение.group(номер_группы)):
            находки.append(причина)
            break  # SECRET_KEY и так подпадает под общий шаблон «secret» — не дублируем
    совпадение_dsn = DSN_POSTGRES_РЕ.search(строка)
    if совпадение_dsn and not похоже_на_заглушку(совпадение_dsn.group(1)):
        находки.append("пароль в postgres DSN")
    if ТОКЕН_TELEGRAM_РЕ.search(строка):
        находки.append("токен Telegram-бота")
    if ПРИВАТНЫЙ_КЛЮЧ_РЕ.search(строка):
        находки.append("приватный ключ (PEM)")
    return находки


def проверить_текст(имя: str, текст: str) -> list:
    находки = []
    for номер, строка in enumerate(текст.splitlines(), 1):
        for причина in проверить_строку(строка):
            находки.append(f"{имя}:{номер} — {причина}")
    return находки


def файл_запрещён_целиком(путь: str) -> str:
    """Причина отказа, если файл — «.env» (кроме «.env.example»); иначе None."""
    имя = Path(путь).name
    if имя == ".env.example":
        return None
    if имя == ".env" or имя.endswith(".env"):
        return "файлы .env в git не попадают — используйте .env.example с заглушками"
    return None


def git(*арг) -> bytes:
    return subprocess.run(["git", *арг], cwd=КОРЕНЬ, capture_output=True, check=True).stdout


def проверить_индекс() -> list:
    находки = []
    for путь in git("diff", "--cached", "--name-only", "-z").decode().split("\0"):
        if not путь:
            continue
        причина_целиком = файл_запрещён_целиком(путь)
        if причина_целиком:
            находки.append(f"{путь} — {причина_целиком}")
            continue
        try:
            содержимое = git("show", f":{путь}")
        except subprocess.CalledProcessError:
            continue  # файл удалён из индекса
        находки += проверить_текст(путь, содержимое.decode(errors="replace"))
    return находки


def main(арг: list) -> int:
    находки = проверить_индекс()
    if находки:
        print("ОТКАЗ: похоже на секрет в коммите (значения не показаны):")
        for н in находки:
            print("  " + н)
        print("Замени значение на *** (или ${VAR}/чтение из окружения) и повтори.")
        return 1
    print("секретов в индексе не найдено")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
