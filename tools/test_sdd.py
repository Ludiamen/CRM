def запустить(*args):
    """Вызывает sdd.main(args), возвращает (код_выхода, stdout, stderr)."""
    буфер_вывод = io.StringIO()
    буфер_ошибок = io.StringIO()
    with contextlib.redirect_stdout(буфер_вывод), contextlib.redirect_stderr(буфер_ошибок):
        код = sdd.main(list(args))
    return код, буфер_вывод.getvalue(), буфер_ошибок.getvalue()


def записать_файл(путь: Path, текст: str) -> None:
    путь.parent.mkdir(parents=True, exist_ok=True)
    путь.write_text(текст, encoding="utf-8")


def собрать_документ_текст(
    id, вид, статус, версия="1", зависит_от=None, основан_на=None,
    проверяет=None, подписи=None, тело="\n# Документ\n",
) -> str:
    строки = ["---", f"id: {id}", f"вид: {вид}", f"статус: {статус}", f"версия: {версия}"]
    if зависит_от:
        строки.append("зависит_от: " + ", ".join(зависит_от))
    if основан_на:
        строки.append(f"основан_на: {основан_на}")
    if проверяет:
        строки.append(f"проверяет: {проверяет}")
    for подпись in (подписи or []):
        строки.append(f"подпись: {подпись}")
    строки.append("---")
    return "\n".join(строки) + тело


def создать_отчёт(root: Path, id_документа: str, отпечаток: str, статус: str = "черновик") -> Path:
    путь = root / "docs" / "reviews" / f"{id_документа}.md"
    текст = собрать_документ_текст(
        f"REV-{id_документа}", "отчёт", статус,
        проверяет=f"{id_документа} {отпечаток}",
        тело="\n# Отчёт проверки\n\nВердикт: годен к подписи.\n",
    )
    записать_файл(путь, текст)
    return путь


def настроить_конституцию(root: Path, инварианты: list, проверять=None) -> dict:
    """Создаёт constitution.json + CONST (черновик) и сразу собирает блок в .md."""
    данные = {"проверять": проверять or [], "инварианты": инварианты}
    записать_файл(root / "docs" / "constitution.json", json.dumps(данные, ensure_ascii=False, indent=2))
    записать_файл(
        root / "docs" / "constitution.md",
        собрать_документ_текст(
            "CONST", "конституция", "черновик",
            тело="\n# Конституция\n\n<!-- из constitution.json: начало -->\n<!-- из constitution.json: конец -->\n",
        ),
    )
    код, _, ошибки = запустить("собрать-конституцию", "--корень", str(root))
    assert код == 0, ошибки
    return данные


@contextlib.contextmanager
def без_claudecode():
    старое = os.environ.pop("CLAUDECODE", None)
    try:
        yield
    finally:
        if старое is not None:
            os.environ["CLAUDECODE"] = старое


@contextlib.contextmanager
def с_claudecode():
    старое = os.environ.get("CLAUDECODE")
    os.environ["CLAUDECODE"] = "1"
    try:
        yield
    finally:
        if старое is None:
            os.environ.pop("CLAUDECODE", None)
        else:
            os.environ["CLAUDECODE"] = старое


class БазовыйСлучай(unittest.TestCase):
    def setUp(self):
        каталог = tempfile.mkdtemp(prefix="sdd-test-")
        self.addCleanup(shutil.rmtree, каталог, ignore_errors=True)
        self.root = Path(каталог)
        (self.root / "docs").mkdir(parents=True, exist_ok=True)
        (self.root / "specs").mkdir(parents=True, exist_ok=True)

    def отпечаток_файла(self, путь: Path) -> str:
        _, вывод, ошибки = запустить("отпечаток", str(путь), "--корень", str(self.root))
        self.assertEqual(вывод.strip() == "", False, ошибки)
        return вывод.strip()


