# Действующий статус: подпись/отчёт устаревают


class ТестДействующегоСтатуса(БазовыйСлучай):
    def test_подпись_устаревает_после_правки_тела(self):
        путь = self.root / "docs" / "b.md"
        записать_файл(путь, собрать_документ_текст("DOC-B", "adr", "черновик", тело="\n# B\n\nПервый текст.\n"))
        отпечаток = self.отпечаток_файла(путь)
        создать_отчёт(self.root, "DOC-B", отпечаток)

        with без_claudecode():
            код, _, ошибки = запустить("подписать", str(путь), "--кто", "Максим", "--корень", str(self.root))
        self.assertEqual(код, 0, ошибки)

        # правим тело после утверждения — подпись должна устареть
        текст_утверждённого = путь.read_text(encoding="utf-8")
        текст_с_новым_телом = текст_утверждённого.replace("Первый текст.", "Другой текст.")
        путь.write_text(текст_с_новым_телом, encoding="utf-8")

        код, вывод, _ = запустить("проверить", "--корень", str(self.root))
        self.assertNotEqual(код, 0)
        self.assertIn("подпись устарела: документ правили после утверждения", вывод)

    def test_нет_подписи_у_утверждённого(self):
        путь = self.root / "docs" / "b2.md"
        записать_файл(путь, собрать_документ_текст("DOC-B2", "adr", "утверждён", тело="\n# B2\n"))
        код, вывод, _ = запустить("проверить", "--корень", str(self.root))
        self.assertNotEqual(код, 0)
        self.assertIn("нет подписи", вывод)

    def test_отчёт_проверки_устарел_или_отсутствует(self):
        путь = self.root / "docs" / "b3.md"
        записать_файл(путь, собрать_документ_текст("DOC-B3", "спека", "на-проверке", тело="\n# B3\n"))
        код, вывод, _ = запустить("проверить", "--корень", str(self.root))
        self.assertNotEqual(код, 0)
        self.assertIn("отчёт проверки устарел/отсутствует", вывод)

        # неверный отпечаток в отчёте — тоже устарел/отсутствует
        отпечаток = self.отпечаток_файла(путь)
        создать_отчёт(self.root, "DOC-B3", "0" * 64)
        self.assertNotEqual(отпечаток, "sha256:" + "0" * 64)
        код2, вывод2, _ = запустить("проверить", "--корень", str(self.root))
        self.assertNotEqual(код2, 0)
        self.assertIn("отчёт проверки устарел/отсутствует", вывод2)


