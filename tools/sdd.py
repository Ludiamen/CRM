# Действующий статус: подпись и отчёт проверки


def найти_отчёт_проверки(документ: Документ, root: Path):
    путь_отчёта = root / "docs" / "reviews" / f"{документ.id}.md"
    if not путь_отчёта.is_file():
        return None
    отчёт, ошибка = разобрать_документ(прочитать_текст(путь_отчёта), путь_отчёта, root)
    if отчёт is None or ошибка:
        return None
    return отчёт


def проверить_отчёт(документ: Документ, root: Path):
    """None, если есть действующий отчёт проверки; иначе текст ошибки."""
    отчёт = найти_отчёт_проверки(документ, root)
    if отчёт is None or отчёт.проверяет is None:
        return "отчёт проверки устарел/отсутствует"
    проверяемый_id, hex_ = отчёт.проверяет
    if проверяемый_id != документ.id or not hex_:
        return "отчёт проверки устарел/отсутствует"
    if f"sha256:{hex_}" != документ.отпечаток:
        return "отчёт проверки устарел/отсутствует"
    return None


def действующий_статус(документ: Документ, документы_по_id: dict, root: Path):
    """Возвращает (действующий_статус, сообщения) по правилам п.2 процесса."""
    статус = документ.статус
    эффективный = статус
    сообщения = []

    if статус == "утверждён":
        if not документ.подписи_разобранные:
            сообщения.append("нет подписи")
            эффективный = "черновик"
        else:
            совпадает = any(
                sha and f"sha256:{sha}" == документ.отпечаток
                for (_, _, sha) in документ.подписи_разобранные
            )
            if not совпадает:
                сообщения.append("подпись устарела: документ правили после утверждения")
                эффективный = "черновик"

    if статус in ("на-проверке", "утверждён"):
        ошибка = проверить_отчёт(документ, root)
        if ошибка:
            сообщения.append(ошибка)
            эффективный = "черновик"

    return эффективный, сообщения


def найти_маркеры_уточнения(документ: Документ) -> list:
    # Маркер в `обратных кавычках` — это упоминание («нет маркеров
    # `[НУЖНО УТОЧНИТЬ]`»), а не открытый вопрос. Кодовые вставки заменяются
    # пробелами той же длины, чтобы номера строк не сдвинулись.
    тело = КОДОВАЯ_ВСТАВКА_РЕ.sub(lambda м: " " * len(м.group(0)), документ.тело)
    return [
        документ.тело_начало_строка + тело.count("\n", 0, м.start())
        for м in МАРКЕР_УТОЧНЕНИЯ_РЕ.finditer(тело)
    ]


def подсчитать_строки_файла(путь: Path) -> int:
    try:
        данные = путь.read_bytes()
    except OSError:
        return -1
    if not данные:
        return 0
    n = данные.count(b"\n")
    if not данные.endswith(b"\n"):
        n += 1
    return n


def проверить_ссылки_на_код(документ: Документ, root: Path) -> list:
    """Список (номер_строки, текст_ссылки, причина) для битых ссылок на код нового стека."""
    находки = []
    for совпадение in ССЫЛКА_НА_КОД.finditer(документ.тело):
        ссылка_текст = совпадение.group(0)
        относительный_путь = совпадение.group(1)
        начало = int(совпадение.group(2))
        конец = int(совпадение.group(3)) if совпадение.group(3) else начало
        нужно_строк = max(начало, конец)
        номер_строки = документ.тело_начало_строка + документ.тело.count("\n", 0, совпадение.start())
        целевой = root / относительный_путь
        if not целевой.is_file():
            находки.append((номер_строки, ссылка_текст, "файл не найден"))
            continue
        число_строк = подсчитать_строки_файла(целевой)
        if число_строк < нужно_строк:
            находки.append(
                (номер_строки, ссылка_текст, f"в файле только {число_строк} строк(и), а нужно {нужно_строк}")
            )
    return находки


def собрать_реестр_источников(root: Path) -> set:
    """Коды SRC-NN, зарегистрированные в docs/reference/sources.md."""
    путь = root / ПУТЬ_РЕЕСТРА_ИСТОЧНИКОВ
    if not путь.is_file():
        return set()
    коды = set()
    for строка in прочитать_текст(путь).split("\n"):
        очищенная = строка.strip()
        if очищенная.startswith("#"):
            совпадение = СС_НА_ИСТОЧНИК_РЕ.search(очищенная)
            if совпадение:
                коды.add(совпадение.group(0))
            continue
        if очищенная.startswith("|"):
            совпадение2 = re.match(r"^\|\s*(SRC-\d+)\b", очищенная)
            if совпадение2:
                коды.add(совпадение2.group(1))
    return коды


def проверить_ссылки_на_источники(документ: Документ, root: Path, реестр: set = None) -> list:
    """Список (номер_строки, SRC-код, причина) для незарегистрированных источников.

    Сам реестр (docs/reference/sources.md) на свои же упоминания не проверяется —
    там SRC-NN это регистрация, а не использование.
    """
    if документ.путь_отн == ПУТЬ_РЕЕСТРА_ИСТОЧНИКОВ:
        return []
    if реестр is None:
        реестр = собрать_реестр_источников(root)
    # Упоминание в `кодовой вставке` — это пример разметки, а не ссылка на
    # источник, как и с маркером уточнения выше.
    тело = КОДОВАЯ_ВСТАВКА_РЕ.sub(lambda м: " " * len(м.group(0)), документ.тело)
    находки = []
    for совпадение in СС_НА_ИСТОЧНИК_РЕ.finditer(тело):
        код = совпадение.group(0)
        if код in реестр:
            continue
        номер_строки = документ.тело_начало_строка + тело.count("\n", 0, совпадение.start())
        находки.append((номер_строки, код, "источник не зарегистрирован"))
    return находки


def условия_утверждения(документ: Документ, документы_по_id: dict, root: Path) -> list:
    """Причины отказа в подписи (пункты 2-5 процесса). Пустой список — можно подписывать."""
    причины = []

    ошибка_отчёта = проверить_отчёт(документ, root)
    if ошибка_отчёта:
        причины.append(ошибка_отчёта)

    маркеры = найти_маркеры_уточнения(документ)
    if маркеры:
        причины.append(
            "в тексте остались маркеры [НУЖНО УТОЧНИТЬ] (строки: " + ", ".join(map(str, маркеры)) + ")"
        )

    for dep_id in документ.зависит_от:
        dep = документы_по_id.get(dep_id)
        if dep is None:
            причины.append(f"зависимость «{dep_id}» не найдена")
        else:
            эфф, _ = действующий_статус(dep, документы_по_id, root)
            if эфф != "утверждён":
                причины.append(f"зависимость «{dep_id}» не утверждена")

    if документ.основан_на:
        base_id, base_hex = документ.основан_на
        base_doc = документы_по_id.get(base_id)
        if base_doc is None:
            причины.append(f"документ-основа «{base_id}» не найден")
        elif not base_hex or f"sha256:{base_hex}" != base_doc.отпечаток:
            причины.append("основа изменилась после планирования")

    for номер, ссылка, причина_ссылки in проверить_ссылки_на_код(документ, root):
        причины.append(f"битая ссылка на код в строке {номер}: {ссылка} — {причина_ссылки}")

    for номер, ссылка, причина_ссылки in проверить_ссылки_на_источники(документ, root):
        причины.append(f"незарегистрированный источник в строке {номер}: {ссылка} — {причина_ссылки}")

    return причины


