def прочитать_конституцию(root: Path):
    """Возвращает (данные|None, ошибки). данные=None — конституции нет вовсе."""
    путь = root / "docs" / "constitution.json"
    if not путь.is_file():
        return None, []
    try:
        данные = json.loads(путь.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as e:
        return None, [f"docs/constitution.json: не удаётся разобрать JSON — {e}"]
    return данные, []


def проверить_инварианты(данные) -> list:
    ошибки = []
    if данные is None:
        return ошибки
    инварианты = данные.get("инварианты", []) or []
    коды = {}
    for i, инв in enumerate(инварианты):
        метка = инв.get("код") or f"#{i + 1}"
        for ключ in ("код", "правило", "вид", "тип", "почему", "вместо", "статус"):
            if not str(инв.get(ключ, "") or "").strip():
                ошибки.append(f"constitution.json: инвариант {метка} — не заполнено поле «{ключ}»")
        тип = инв.get("тип")
        if тип and тип not in ТИПЫ_ИНВАРИАНТОВ:
            ошибки.append(f"constitution.json: инвариант {метка} — неизвестный тип «{тип}»")
        elif тип in ТИПЫ_ЖЁСТКИЕ:
            значения = инв.get("значения") or []
            if not значения:
                ошибки.append(
                    f"constitution.json: инвариант {метка} — непроверяемый запрет хуже отсутствующего "
                    f"(нет «значений»)"
                )
            elif тип == "запрет-регулярок":
                for рег in значения:
                    try:
                        re.compile(рег)
                    except re.error as e:
                        ошибки.append(
                            f"constitution.json: инвариант {метка} — регулярка «{рег}» не компилируется: {e}"
                        )
        код = инв.get("код")
        if код:
            коды.setdefault(код, []).append(метка)
    for код, вхожд in коды.items():
        if len(вхожд) > 1:
            ошибки.append(f"constitution.json: код «{код}» повторяется {len(вхожд)} раз(а)")
    return ошибки


def проверить_конституцию_утверждена(данные, документы_по_id: dict, root: Path) -> list:
    ошибки = []
    if данные is None:
        return ошибки
    конст = документы_по_id.get("CONST")
    if конст is None:
        return ошибки
    эфф, _ = действующий_статус(конст, документы_по_id, root)
    if эфф != "утверждён":
        return ошибки
    for инв in данные.get("инварианты", []) or []:
        if инв.get("статус") == "предложен":
            ошибки.append(
                f"constitution.json: конституция утверждена, а инвариант «{инв.get('код')}» "
                f"имеет статус «предложен»"
            )
    return ошибки


def _с_большой_буквы(слово: str) -> str:
    return слово[:1].upper() + слово[1:] if слово else слово


def собрать_блок_конституции(данные: dict) -> str:
    """Строит текст блока между метками из данных constitution.json."""
    инварианты = данные.get("инварианты", []) or []
    группы = {}
    for инв in инварианты:
        группы.setdefault(инв.get("вид", "прочие"), []).append(инв)
    известные = [в for в in ПОРЯДОК_ВИДОВ_ИНВАРИАНТОВ if в in группы]
    прочие = sorted(в for в in группы if в not in ПОРЯДОК_ВИДОВ_ИНВАРИАНТОВ)

    строки = []
    for вид in известные + прочие:
        строки.append(f"## {_с_большой_буквы(вид)}")
        строки.append("")
        for инв in группы[вид]:
            строки.append(f"### {инв.get('код', '')} — {инв.get('статус', '')}")
            строки.append(инв.get("правило", ""))
            строки.append("")
            строки.append(f"- **Почему:** {инв.get('почему', '')}")
            строки.append(f"- **Вместо:** {инв.get('вместо', '')}")
            тип = инв.get("тип")
            if тип == "смысловой":
                проверка = "на воротах, проверяющим"
            else:
                значения = инв.get("значения") or []
                проверка = f"{тип}: " + ", ".join(f"`{з}`" for з in значения)
            строки.append(f"- **Проверка:** {проверка}")
            строки.append(f"- **Источник:** {инв.get('источник', '')}")
            строки.append("")
    return "\n".join(строки).rstrip("\n")


def проверить_синхронность_constitution_md(данные, root: Path) -> list:
    if данные is None:
        return []
    путь_md = root / "docs" / "constitution.md"
    if not путь_md.is_file():
        return ["docs/constitution.md: файл отсутствует, хотя docs/constitution.json есть"]
    текст = прочитать_текст(путь_md)
    if МЕТКА_НАЧАЛО not in текст or МЕТКА_КОНЕЦ not in текст:
        return ["docs/constitution.md: не найдена разметка блока «из constitution.json»"]
    начало = текст.index(МЕТКА_НАЧАЛО) + len(МЕТКА_НАЧАЛО)
    конец = текст.index(МЕТКА_КОНЕЦ)
    if конец < начало:
        return ["docs/constitution.md: метки блока идут в неверном порядке"]
    текущий_блок = текст[начало:конец].strip("\n")
    ожидаемый_блок = собрать_блок_конституции(данные)
    if текущий_блок.strip() != ожидаемый_блок.strip():
        return ["docs/constitution.md отстаёт от constitution.json (нужно запустить sdd.py собрать-конституцию)"]
    return []


def похож_на_текст(путь: Path, предел_байт: int = ПРЕДЕЛ_РАЗМЕРА_ТЕКСТОВОГО_ФАЙЛА) -> bool:
    try:
        if путь.stat().st_size > предел_байт:
            return False
        with open(путь, "rb") as f:
            кусок = f.read(8192)
        if b"\x00" in кусок:
            return False
        кусок.decode("utf-8")
    except (OSError, UnicodeDecodeError):
        return False
    return True


def собрать_файлы_для_проверки(root: Path, шаблоны: list) -> list:
    найденные = set()
    for шаблон in шаблоны:
        for совпадение in glob.glob(str(root / шаблон), recursive=True):
            p = Path(совпадение)
            if p.is_file():
                найденные.add(p.resolve())
    return sorted(найденные, key=lambda p: p.as_posix())


def _нарушение_на_строке(инв: dict, строка: str):
    тип = инв.get("тип")
    значения = инв.get("значения") or []
    if тип == "запрет-слов":
        for слово in значения:
            if re.search(rf"\b{re.escape(слово)}\b", строка, re.IGNORECASE):
                return слово
        return None
    if тип == "запрет-в-коде":
        for подстрока in значения:
            if подстрока in строка:
                return подстрока
        return None
    if тип == "запрет-регулярок":
        for рег in значения:
            try:
                if re.search(рег, строка):
                    return рег
            except re.error:
                continue
        return None
    return None


def проверить_код_по_конституции(данные, root: Path):
    """Возвращает (ошибки, есть_файлы_по_шаблонам)."""
    if данные is None:
        return [], False
    шаблоны = данные.get("проверять", []) or []
    файлы = собрать_файлы_для_проверки(root, шаблоны)
    if not файлы:
        return [], False

    жёсткие = [инв for инв in (данные.get("инварианты", []) or []) if инв.get("тип") in ТИПЫ_ЖЁСТКИЕ]
    ошибки = []
    for файл in файлы:
        if not похож_на_текст(файл):
            continue
        rel = файл.relative_to(root).as_posix()
        try:
            строки = файл.read_text(encoding="utf-8", errors="ignore").split("\n")
        except OSError:
            continue
        for номер, строка in enumerate(строки, start=1):
            for инв in жёсткие:
                if _нарушение_на_строке(инв, строка):
                    ошибки.append(
                        f"{rel}:{номер} [{инв.get('код')}] {инв.get('правило')} — "
                        f"почему: {инв.get('почему')} — вместо: {инв.get('вместо')}"
                    )
    return ошибки, True


