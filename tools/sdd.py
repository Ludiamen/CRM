# Аргументы командной строки


def построить_парсер() -> argparse.ArgumentParser:
    родитель = argparse.ArgumentParser(add_help=False)
    родитель.add_argument(
        "--корень",
        default=None,
        help="корень репозитория (по умолчанию — родитель каталога tools/)",
    )

    парсер = argparse.ArgumentParser(
        prog="sdd.py",
        description="Ворота SDD: проверка статусов, подписей, ссылок на код/источники и конституции проекта.",
    )
    подпарсеры = парсер.add_subparsers(dest="команда", required=True)

    подпарсеры.add_parser("проверить", parents=[родитель], help="проверить все документы, конституцию и код")
    подпарсеры.add_parser("статус", parents=[родитель], help="таблица статусов документов")

    p = подпарсеры.add_parser("отпечаток", parents=[родитель], help="напечатать отпечаток документа")
    p.add_argument("путь")

    p = подпарсеры.add_parser("на-проверку", parents=[родитель], help="перевести документ в статус «на-проверке»")
    p.add_argument("путь")

    p = подпарсеры.add_parser("подписать", parents=[родитель], help="утвердить документ подписью человека")
    p.add_argument("путь")
    p.add_argument("--кто", required=True, help="имя подписывающего")

    подпарсеры.add_parser(
        "собрать-конституцию", parents=[родитель], help="пересобрать читаемый блок в docs/constitution.md"
    )

    return парсер


def main(argv=None) -> int:
    парсер = построить_парсер()
    args = парсер.parse_args(argv)
    root = Path(args.корень).resolve() if args.корень else КОРЕНЬ_ПО_УМОЛЧАНИЮ

    if args.команда == "проверить":
        return cmd_проверить(root)
    if args.команда == "статус":
        return cmd_статус(root)
    if args.команда == "отпечаток":
        return cmd_отпечаток(args.путь, root)
    if args.команда == "на-проверку":
        return cmd_на_проверку(args.путь, root)
    if args.команда == "подписать":
        return cmd_подписать(args.путь, args.кто, root)
    if args.команда == "собрать-конституцию":
        return cmd_собрать_конституцию(root)

    парсер.error("неизвестная команда")
    return 2


if __name__ == "__main__":
    sys.exit(main())
