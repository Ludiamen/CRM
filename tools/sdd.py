РЕШЕНИЯ_КАНОНИЧЕСКИЕ = {"mvp": "MVP", "позже": "позже", "не нужно": "не нужно"}


def _разобрать_строку_таблицы(строка: str) -> list:
    """Разбивает строку markdown-таблицы на ячейки (без краевых «|»)."""
    очищенная = строка.strip()
    if очищенная.startswith("|"):
        очищенная = очищенная[1:]
    if очищенная.endswith("|"):
        очищенная = очищенная[:-1]
    return [ячейка.strip() for ячейка in очищенная.split("|")]


def _строка_разделитель_таблицы(строка: str) -> bool:
    очищенная = строка.strip()
    if not очищенная.startswith("|"):
        return False
    тело = очищенная.strip("|")
    return bool(тело) and all(c in " -:|" for c in тело)


def _найти_таблицы(текст: str) -> list:
    """Список (заголовок, строки_данных) для каждой markdown-таблицы текста."""
    строки = текст.split("\n")
    таблицы = []
    i = 0
    while i < len(строки):
        if строки[i].strip().startswith("|"):
            заголовок = _разобрать_строку_таблицы(строки[i])
            j = i + 1
            if j < len(строки) and _строка_разделитель_таблицы(строки[j]):
                j += 1
            данные = []
            while j < len(строки) and строки[j].strip().startswith("|"):
                данные.append(_разобрать_строку_таблицы(строки[j]))
                j += 1
            таблицы.append((заголовок, данные))
            i = j
        else:
            i += 1
    return таблицы


def _нормализовать_решение(значение: str):
    """('MVP'|'позже'|'не нужно'|None, предупреждение|None) по сырой ячейке."""
    очищенное = (значение or "").strip()
    if not очищенное or очищенное == "—":
        return None, None
    решение = РЕШЕНИЯ_КАНОНИЧЕСКИЕ.get(очищенное.lower())
    if решение is not None:
        return решение, None
    return None, f"неизвестное решение «{очищенное}»"


def собрать_capabilities(root: Path):
    """Возвращает (решения: dict[CAP-NN -> 'MVP'|'позже'|'не нужно'|None], предупреждения)."""
    путь = root / "docs" / "reference" / "capabilities.md"
    if not путь.is_file():
        return {}, []
    текст = прочитать_текст(путь)
    решения: dict = {}
    предупреждения = []

    for заголовок, данные in _найти_таблицы(текст):
        индекс_решения = None
        for i, ячейка in enumerate(заголовок):
            if ячейка.strip().lower() == "решение":
                индекс_решения = i
                break
        if индекс_решения is None:
            continue
        for строка_данных in данные:
            if not строка_данных:
                continue
            совпадение = re.match(r"^(CAP-\d+)\b", строка_данных[0].strip())
            if not совпадение:
                continue
            cap_id = совпадение.group(1)
            сырое = строка_данных[индекс_решения] if индекс_решения < len(строка_данных) else ""
            решение, предупреждение = _нормализовать_решение(сырое)
            решения[cap_id] = решение
            if предупреждение:
                предупреждения.append(f"{cap_id}: {предупреждение}")

    # Заголовки «### CAP-NN» — тоже возможности, но без решения, если строки
    # с решением для них не нашлось ни в одной таблице.
    for строка in текст.split("\n"):
        совпадение = re.match(r"^#{1,6}\s+(CAP-\d+)\b", строка.strip())
        if совпадение:
            решения.setdefault(совпадение.group(1), None)

    return решения, предупреждения


def собрать_покрытые_capabilities(root: Path) -> dict:
    """CAP-NN -> список спек (docs-относительных путей), где он упомянут."""
    покрытие: dict = {}
    for путь_str in glob.glob(str(root / "specs" / "*" / "spec.md")):
        p = Path(путь_str)
        if not p.is_file():
            continue
        rel = p.relative_to(root).as_posix()
        for cap_id in sorted(set(re.findall(r"CAP-\d+", прочитать_текст(p)))):
            покрытие.setdefault(cap_id, []).append(rel)
    return покрытие


def предупреждения_трассировки(решения: dict, покрытие: dict) -> list:
    """Спека ссылается на CAP с решением «не нужно» или на CAP вне карты."""
    предупреждения = []
    for cap_id, спеки in sorted(покрытие.items(), key=lambda kv: (int(kv[0].split("-")[1]), kv[0])):
        for rel in спеки:
            if cap_id not in решения:
                предупреждения.append(f"{rel}: ссылается на {cap_id}, которого нет в карте возможностей")
            elif решения[cap_id] == "не нужно":
                предупреждения.append(f"{rel}: ссылается на {cap_id} с решением «не нужно»")
    return предупреждения


def сводка_трассировки(root: Path):
    """Возвращает (строка_сводки, предупреждения) по карте docs/reference/capabilities.md."""
    решения, предупреждения_решений = собрать_capabilities(root)
    покрытие = собрать_покрытые_capabilities(root)

    счёт = {"MVP": 0, "позже": 0, "не нужно": 0, "без решения": 0}
    mvp_ids = []
    for cap_id, решение in решения.items():
        счёт[решение or "без решения"] += 1
        if решение == "MVP":
            mvp_ids.append(cap_id)

    mvp_покрыто = sum(1 for cap_id in mvp_ids if cap_id in покрытие)
    mvp_не_покрыты = sorted(
        (cap_id for cap_id in mvp_ids if cap_id not in покрытие),
        key=lambda c: int(c.split("-")[1]),
    )

    строка = (
        f"возможностей: {len(решения)} (MVP: {счёт['MVP']}, позже: {счёт['позже']}, "
        f"не нужно: {счёт['не нужно']}, без решения: {счёт['без решения']}); "
        f"MVP покрыто спеками: {mvp_покрыто} из {len(mvp_ids)}"
    )
    if mvp_не_покрыты:
        строка += "; MVP не покрыты: " + ", ".join(mvp_не_покрыты)

    предупреждения = list(предупреждения_решений)
    предупреждения.extend(предупреждения_трассировки(решения, покрытие))
    return строка, предупреждения


