def cmd_проверить(root: Path) -> int:
    документы, документы_по_id, ошибки, предупреждения = собрать_документы(root)
    реестр_источников = собрать_реестр_источников(root)

    for д in документы:
        эфф, сообщения_статуса = действующий_статус(д, документы_по_id, root)
        for m in сообщения_статуса:
            ошибки.append(f"{д.путь_отн}: {m}")

        if д.статус == "утверждён":
            маркеры = найти_маркеры_уточнения(д)
            if маркеры:
                ошибки.append(
                    f"{д.путь_отн}: в тексте остались маркеры [НУЖНО УТОЧНИТЬ] "
                    f"(строки: {', '.join(map(str, маркеры))})"
                )
            for dep_id in д.зависит_от:
                dep = документы_по_id.get(dep_id)
                if dep is None:
                    ошибки.append(f"{д.путь_отн}: зависимость «{dep_id}» не найдена")
                else:
                    эфф_dep, _ = действующий_статус(dep, документы_по_id, root)
                    if эфф_dep != "утверждён":
                        ошибки.append(f"{д.путь_отн}: зависимость «{dep_id}» не утверждена")
        elif д.статус == "черновик":
            for dep_id in д.зависит_от:
                if dep_id not in документы_по_id:
                    предупреждения.append(f"{д.путь_отн}: зависимость «{dep_id}» не найдена")

        if д.основан_на:
            base_id, base_hex = д.основан_на
            base_doc = документы_по_id.get(base_id)
            приёмник = ошибки if д.статус != "черновик" else предупреждения
            if base_doc is None:
                приёмник.append(f"{д.путь_отн}: документ-основа «{base_id}» не найден")
            elif not base_hex or f"sha256:{base_hex}" != base_doc.отпечаток:
                приёмник.append(f"{д.путь_отн}: основа изменилась после планирования")

        for номер, ссылка, причина in проверить_ссылки_на_код(д, root):
            приёмник = ошибки if д.статус != "черновик" else предупреждения
            приёмник.append(f"{д.путь_отн}:{номер}: ссылка {ссылка} — {причина}")

        for номер, ссылка, причина in проверить_ссылки_на_источники(д, root, реестр_источников):
            приёмник = ошибки if д.статус != "черновик" else предупреждения
            приёмник.append(f"{д.путь_отн}:{номер}: ссылка {ссылка} — {причина}")

    данные_json, ошибки_json = прочитать_конституцию(root)
    ошибки.extend(ошибки_json)
    ошибки.extend(проверить_инварианты(данные_json))
    ошибки.extend(проверить_конституцию_утверждена(данные_json, документы_по_id, root))
    ошибки.extend(проверить_синхронность_constitution_md(данные_json, root))
    ошибки_кода, есть_файлы = проверить_код_по_конституции(данные_json, root)
    ошибки.extend(ошибки_кода)

    строка_трассировки, предупреждения_cap = сводка_трассировки(root)
    предупреждения.extend(предупреждения_cap)

    for e in ошибки:
        print(f"ОШИБКА: {e}")
    for w in предупреждения:
        print(f"ПРЕДУПРЕЖДЕНИЕ: {w}")
    if not есть_файлы:
        print("кода нового стека пока нет")
    print(строка_трассировки)
    print(f"документов: {len(документы)}, ошибок: {len(ошибки)}, предупреждений: {len(предупреждения)}")

    return 1 if ошибки else 0


