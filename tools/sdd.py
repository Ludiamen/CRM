# Подкоманда «собрать-конституцию»


def cmd_собрать_конституцию(root: Path) -> int:
    путь_json = root / "docs" / "constitution.json"
    if not путь_json.is_file():
        print("docs/constitution.json не найден", file=sys.stderr)
        return 1
    try:
        данные = json.loads(путь_json.read_text(encoding="utf-8"))
    except json.JSONDecodeError as e:
        print(f"не удаётся разобрать docs/constitution.json: {e}", file=sys.stderr)
        return 1

    путь_md = root / "docs" / "constitution.md"
    if not путь_md.is_file():
        print("docs/constitution.md не найден", file=sys.stderr)
        return 1
    текст = прочитать_текст(путь_md)
    if МЕТКА_НАЧАЛО not in текст or МЕТКА_КОНЕЦ not in текст:
        print("в docs/constitution.md не найдена разметка блока «из constitution.json»", file=sys.stderr)
        return 1

    блок = собрать_блок_конституции(данные)
    начало = текст.index(МЕТКА_НАЧАЛО) + len(МЕТКА_НАЧАЛО)
    конец = текст.index(МЕТКА_КОНЕЦ)
    новый_текст = текст[:начало] + "\n" + блок + "\n" + текст[конец:]
    путь_md.write_text(новый_текст, encoding="utf-8")
    число_инвариантов = len(данные.get("инварианты", []) or [])
    print(f"docs/constitution.md обновлён: {число_инвариантов} инвариантов")
    return 0


