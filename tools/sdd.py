# Подкоманда «статус»


def cmd_статус(root: Path) -> int:
    документы, документы_по_id, _, _ = собрать_документы(root)
    заголовки = ("id", "вид", "статус(файл)", "действующий", "путь", "отпечаток", "подписи")
    строки_таблицы = [заголовки]
    for д in sorted(документы, key=lambda d: d.id):
        эфф, _ = действующий_статус(д, документы_по_id, root)
        короткий = д.отпечаток.split(":", 1)[-1][:12]
        подписи_текст = "; ".join(f"{кто} ({время})" for кто, время, _ in д.подписи_разобранные) or "—"
        строки_таблицы.append((д.id, д.вид, д.статус, эфф, д.путь_отн, короткий, подписи_текст))

    ширины = [max(len(строка[i]) for строка in строки_таблицы) for i in range(len(заголовки))]
    for строка in строки_таблицы:
        print("  ".join(значение.ljust(ширина) for значение, ширина in zip(строка, ширины)))
    return 0


