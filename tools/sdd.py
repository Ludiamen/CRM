#!/usr/bin/env python3
"""Ворота SDD для CRM/портала ИТ-отдела.

Инструмент читает документы `docs/**/*.md` и `specs/**/*.md`, проверяет их
frontmatter, подписи и отпечатки, ссылки на код нового стека и на
зарегистрированные источники (SRC-NN), конституцию проекта
(`docs/constitution.json`) и сам код — по правилам из `docs/sdd-process.md`.
Только стандартная библиотека Python 3.12 (в проекте нет PyYAML), формат
frontmatter — плоский «ключ: значение».

Подкоманды:
    проверить            — полная проверка репозитория, печатает ошибки/предупреждения
    статус               — таблица статусов всех документов
    отпечаток ПУТЬ        — печатает отпечаток тела документа
    на-проверку ПУТЬ      — черновик → на-проверке (нужен отчёт проверки)
    подписать ПУТЬ --кто ИМЯ — на-проверке → утверждён (только человек)
    собрать-конституцию   — пересобирает читаемый блок в docs/constitution.md

Корень репозитория по умолчанию — родитель каталога tools/, где лежит этот
файл (не текущий каталог). Для проверки во временном каталоге (тесты) у
каждой подкоманды есть необязательный `--корень ПУТЬ`.

Примеры:
    python3 tools/sdd.py проверить
    python3 tools/sdd.py статус
    python3 tools/sdd.py отпечаток docs/reference/capabilities.md
    python3 tools/sdd.py на-проверку specs/001-servicedesk/spec.md
    python3 tools/sdd.py подписать docs/constitution.md --кто Максим
    python3 tools/sdd.py собрать-конституцию
"""

