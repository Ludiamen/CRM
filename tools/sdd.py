def cmd_на_проверку(путь_строка: str, root: Path) -> int:
    документ, путь, ошибка = _загрузить_документ_по_пути(путь_строка, root)
    if документ is None:
        print(ошибка, file=sys.stderr)
        return 1
    ошибка_отчёта = проверить_отчёт(документ, root)
    if ошибка_отчёта:
        print(
            f"отказ: {ошибка_отчёта} — нужен docs/reviews/{документ.id}.md со строкой "
            f"«проверяет: {документ.id} {документ.отпечаток}»",
            file=sys.stderr,
        )
        return 1
    новый_текст = заменить_статус_в_frontmatter(прочитать_текст(путь), "на-проверке")
    путь.write_text(новый_текст, encoding="utf-8")
    print(f"{документ.путь_отн}: статус → на-проверке")
    return 0


