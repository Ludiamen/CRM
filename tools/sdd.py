# Подкоманда «подписать»


def cmd_подписать(путь_строка: str, кто: str, root: Path) -> int:
    if "CLAUDECODE" in os.environ:
        print(
            "отказ: подпись ставит человек в своём терминале — модель документ не утверждает.",
            file=sys.stderr,
        )
        return 1

    документ, путь, ошибка = _загрузить_документ_по_пути(путь_строка, root)
    if документ is None:
        print(ошибка, file=sys.stderr)
        return 1

    _, документы_по_id, _, _ = собрать_документы(root)
    причины = условия_утверждения(документ, документы_по_id, root)
    if причины:
        print("отказ: документ не готов к утверждению:", file=sys.stderr)
        for причина in причины:
            print(f"  - {причина}", file=sys.stderr)
        return 1

    строка_подписи = f"{кто} | {текущее_время_iso()} | {документ.отпечаток}"
    новый_текст = заменить_статус_в_frontmatter(прочитать_текст(путь), "утверждён")
    новый_текст = вставить_подпись_в_frontmatter(новый_текст, строка_подписи)
    путь.write_text(новый_текст, encoding="utf-8")
    print(f"{документ.путь_отн}: утверждён, подпись — {кто}")
    return 0


