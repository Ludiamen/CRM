# --------------------------------------------------------------------------
# Константы формата

ВИДЫ = {
    "конституция", "процесс", "adr", "эталон", "требования", "архитектура",
    "спека", "план", "задачи", "отчёт",
}
СТАТУСЫ = {"черновик", "на-проверке", "утверждён", "заменён"}

ТИПЫ_ЖЁСТКИЕ = {"запрет-слов", "запрет-в-коде", "запрет-регулярок"}
ТИПЫ_ИНВАРИАНТОВ = ТИПЫ_ЖЁСТКИЕ | {"смысловой"}

ПОРЯДОК_ВИДОВ_ИНВАРИАНТОВ = ["стек", "архитектура", "бизнес-правило", "безопасность", "процесс"]

МАРКЕР_УТОЧНЕНИЯ = "[НУЖНО УТОЧНИТЬ"
# Маркер ищется с запасом на опечатки: модели пишут «[НУЮНО УТОЧНИТЬ» и
# «[Нужно уточнить», и такой маркер, найденный строгим сравнением, молча
# пропустил бы неотвеченный вопрос на ворота.
КОДОВАЯ_ВСТАВКА_РЕ = re.compile(r"`[^`\n]*`")
МАРКЕР_УТОЧНЕНИЯ_РЕ = re.compile(r"\[\s*НУ\w{1,4}\s+УТОЧН\w*", re.IGNORECASE)

МЕТКА_НАЧАЛО = "<!-- из constitution.json: начало -->"
МЕТКА_КОНЕЦ = "<!-- из constitution.json: конец -->"

# backend/… | frontend/… | deploy/… | tools/… | templates/…: путь.расширение:NN[-MM]
ССЫЛКА_НА_КОД = re.compile(
    r"\b((?:backend|frontend|deploy|tools|templates)/[\w./\-]+?"
    r"\.(?:py|html|js|ts|css|json|yml|yaml|toml|sh|md|txt|sql))"
    r":(\d+)(?:-(\d+))?"
)

# Упоминание источника из docs/reference/sources.md — SRC-NN.
СС_НА_ИСТОЧНИК_РЕ = re.compile(r"\bSRC-\d+\b")
ПУТЬ_РЕЕСТРА_ИСТОЧНИКОВ = "docs/reference/sources.md"

ПРЕДЕЛ_РАЗМЕРА_ТЕКСТОВОГО_ФАЙЛА = 1_048_576  # 1 МБ

КОРЕНЬ_ПО_УМОЛЧАНИЮ = Path(__file__).resolve().parent.parent


# --------------------------------------------------------------------------
# Модель документа


@dataclasses.dataclass
class Документ:
    путь: Path
    путь_отн: str
    id: str
    вид: str
    статус: str
    версия: str
    зависит_от: list
    основан_на: object  # tuple[str, str] | None
    проверяет: object  # tuple[str, str] | None
    подписи: list  # сырые строки после "подпись: "
    подписи_разобранные: list  # list[tuple[кто, время, sha_hex|None]]
    тело: str
    тело_начало_строка: int
    отпечаток: str


def прочитать_текст(путь: Path) -> str:
    return путь.read_text(encoding="utf-8")


_ОТМЕТКА_ЗАДАЧИ = re.compile(r"^([ \t]*)- \[[xX]\]", re.MULTILINE)


def вычислить_отпечаток(тело: str, вид: str = "") -> str:
    """sha256 тела документа, нормализованного по правилам процесса SDD.

    У документа вида «задачи» отметка выполнения `- [x]` считается равной
    `- [ ]`: подпись держится, пока правят не текст задач, а только отметки.
    """
    нормализованное = тело.replace("\r\n", "\n")
    if вид == "задачи":
        нормализованное = _ОТМЕТКА_ЗАДАЧИ.sub(r"\1- [ ]", нормализованное)
    строки = [строка.rstrip() for строка in нормализованное.split("\n")]
    нормализованное = "\n".join(строки).strip("\n")
    return "sha256:" + hashlib.sha256(нормализованное.encode("utf-8")).hexdigest()


def _распарсить_ссылку_с_отпечатком(значение):
    """«ID sha256:hex» → (ID, hex в нижнем регистре); None, если значения нет."""
    if not значение:
        return None
    значение = значение.strip()
    совпадение = re.match(r"^(\S+)\s+sha256:([0-9a-fA-F]+)", значение)
    if not совпадение:
        return (значение.split()[0] if значение.split() else значение, "")
    return (совпадение.group(1), совпадение.group(2).lower())


def _распарсить_подпись(значение: str):
    """«кто | время | sha256:hex» → (кто, время, hex_в_нижнем_регистре|None)."""
    части = [часть.strip() for часть in значение.split("|")]
    кто = части[0] if части else ""
    время = части[1] if len(части) > 1 else ""
    sha = None
    if части:
        совпадение = re.search(r"sha256:([0-9a-fA-F]+)", части[-1])
        if совпадение:
            sha = совпадение.group(1).lower()
    return (кто, время, sha)


def найти_границы_frontmatter(строки: list):
    """Индекс закрывающей строки «---» или None, если открывающей нет/не закрыта.

    Возвращает (закрывающая_строка, ошибка). Если первая строка — не «---»,
    возвращает (None, None): frontmatter просто отсутствует. Если открывающая
    есть, а закрывающей нет — (None, текст ошибки).
    """
    if not строки or строки[0].strip() != "---":
        return None, None
    for i in range(1, len(строки)):
        if строки[i].strip() == "---":
            return i, None
    return None, "не найдена закрывающая строка frontmatter «---»"


def разобрать_документ(текст: str, путь: Path, root: Path):
    """Разбирает документ на Документ. Возвращает (Документ|None, ошибка_структуры|None).

    Документ is None и ошибка None — frontmatter отсутствует вовсе (не открыт).
    Документ is None и ошибка непустая — открыт, но не закрыт (структурная ошибка).
    """
    строки = текст.split("\n")
    закрывающая, ошибка = найти_границы_frontmatter(строки)
    if ошибка:
        return None, ошибка
    if закрывающая is None:
        return None, None

    сырые: dict = {}
    подписи_raw: list = []
    for i in range(1, закрывающая):
        строка = строки[i]
        очищенная = строка.strip()
        if not очищенная or очищенная.startswith("#"):
            continue
        if ":" not in строка:
            continue
        ключ, _, значение = строка.partition(":")
        ключ = ключ.strip()
        значение = значение.strip()
        if ключ == "подпись":
            подписи_raw.append(значение)
        else:
            сырые[ключ] = значение

    зависит_от_raw = сырые.get("зависит_от", "")
    зависит_от = [x.strip() for x in зависит_от_raw.split(",") if x.strip()]

    тело_начало_строка = закрывающая + 2
    тело = "\n".join(строки[закрывающая + 1:])
    отпечаток = вычислить_отпечаток(тело, сырые.get("вид", "").strip())

    try:
        путь_отн = путь.resolve().relative_to(root.resolve()).as_posix()
    except ValueError:
        путь_отн = путь.as_posix()

    документ = Документ(
        путь=путь,
        путь_отн=путь_отн,
        id=сырые.get("id", "").strip(),
        вид=сырые.get("вид", "").strip(),
        статус=сырые.get("статус", "").strip(),
        версия=сырые.get("версия", "").strip(),
        зависит_от=зависит_от,
        основан_на=_распарсить_ссылку_с_отпечатком(сырые.get("основан_на")),
        проверяет=_распарсить_ссылку_с_отпечатком(сырые.get("проверяет")),
        подписи=подписи_raw,
        подписи_разобранные=[_распарсить_подпись(s) for s in подписи_raw],
        тело=тело,
        тело_начало_строка=тело_начало_строка,
        отпечаток=отпечаток,
    )
    return документ, None


def проверить_обязательные_ключи(документ: Документ) -> list:
    сообщения = []
    if not документ.id:
        сообщения.append("не заполнен обязательный ключ «id»")
    if not документ.вид:
        сообщения.append("не заполнен обязательный ключ «вид»")
    elif документ.вид not in ВИДЫ:
        сообщения.append(f"недопустимое значение «вид»: {документ.вид}")
    if not документ.статус:
        сообщения.append("не заполнен обязательный ключ «статус»")
    elif документ.статус not in СТАТУСЫ:
        сообщения.append(f"недопустимое значение «статус»: {документ.статус}")
    if not документ.версия:
        сообщения.append("не заполнен обязательный ключ «версия»")
    return сообщения


ПРЕФИКСЫ_С_ОБЯЗАТЕЛЬНЫМ_FRONTMATTER = (
    "docs/reference/", "docs/requirements/", "docs/target/", "docs/decisions/", "specs/",
)


def требует_frontmatter(путь_отн: str) -> bool:
    return путь_отн.startswith(ПРЕФИКСЫ_С_ОБЯЗАТЕЛЬНЫМ_FRONTMATTER)


def найти_markdown_пути(root: Path) -> list:
    пути = set()
    for шаблон in ("docs/**/*.md", "specs/**/*.md"):
        for совпадение in glob.glob(str(root / шаблон), recursive=True):
            p = Path(совпадение)
            if p.is_file():
                пути.add(p.resolve())
    return sorted(пути, key=lambda p: p.as_posix())


def собрать_документы(root: Path):
    """Возвращает (документы, документы_по_id, ошибки, предупреждения)."""
    ошибки = []
    предупреждения = []
    документы = []
    for путь in найти_markdown_пути(root):
        rel = путь.relative_to(root).as_posix()
        текст = прочитать_текст(путь)
        документ, ошибка_структуры = разобрать_документ(текст, путь, root)
        if документ is None:
            if ошибка_структуры:
                ошибки.append(f"{rel}: {ошибка_структуры}")
            elif требует_frontmatter(rel):
                ошибки.append(
                    "{}: отсутствует frontmatter (обязателен для {} и specs)".format(
                        rel, ", ".join(p.rstrip("/") for p in ПРЕФИКСЫ_С_ОБЯЗАТЕЛЬНЫМ_FRONTMATTER[:-1])
                    )
                )
            continue
        документы.append(документ)
        ошибки.extend(f"{rel}: {сообщение}" for сообщение in проверить_обязательные_ключи(документ))

    документы_по_id = {}
    повторы = {}
    for д in документы:
        if not д.id:
            continue
        if д.id in документы_по_id:
            повторы.setdefault(д.id, [документы_по_id[д.id].путь_отн]).append(д.путь_отн)
        else:
            документы_по_id[д.id] = д
    for id_, пути_список in повторы.items():
        ошибки.append(f"id «{id_}» повторяется: {', '.join(пути_список)}")

    return документы, документы_по_id, ошибки, предупреждения


