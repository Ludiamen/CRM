# Путь документа из аргумента командной строки


def определить_путь(root: Path, путь_строка: str) -> Path:
    p = Path(путь_строка)
    if p.is_absolute():
        return p
    кандидат_cwd = Path.cwd() / p
    if кандидат_cwd.exists():
        return кандидат_cwd.resolve()
    return (root / p).resolve()


def _загрузить_документ_по_пути(путь_строка: str, root: Path):
    """(документ, путь, None) при успехе; (None, путь, сообщение_ошибки) при неудаче."""
    путь = определить_путь(root, путь_строка)
    if not путь.is_file():
        return None, путь, f"файл не найден: {путь}"
    документ, ошибка_структуры = разобрать_документ(прочитать_текст(путь), путь, root)
    if документ is None:
        return None, путь, f"не удалось разобрать frontmatter: {ошибка_структуры or 'frontmatter отсутствует'}"
    return документ, путь, None


