# Правка frontmatter на месте (статус, добавление подписи)


def заменить_статус_в_frontmatter(текст: str, новый_статус: str) -> str:
    строки = текст.split("\n")
    закрывающая, ошибка = найти_границы_frontmatter(строки)
    if закрывающая is None:
        raise ValueError(ошибка or "frontmatter отсутствует")
    for i in range(1, закрывающая):
        очищенная = строки[i].strip()
        if not очищенная or очищенная.startswith("#") or ":" not in строки[i]:
            continue
        ключ = строки[i].split(":", 1)[0].strip()
        if ключ == "статус":
            строки[i] = f"статус: {новый_статус}"
            break
    return "\n".join(строки)


def вставить_подпись_в_frontmatter(текст: str, строка_подписи: str) -> str:
    строки = текст.split("\n")
    закрывающая, ошибка = найти_границы_frontmatter(строки)
    if закрывающая is None:
        raise ValueError(ошибка or "frontmatter отсутствует")
    строки.insert(закрывающая, f"подпись: {строка_подписи}")
    return "\n".join(строки)


def текущее_время_iso() -> str:
    сейчас = datetime.datetime.now().astimezone()
    смещение = сейчас.strftime("%z") or "+0000"
    смещение_с_двоеточием = f"{смещение[:3]}:{смещение[3:]}"
    return сейчас.strftime("%Y-%m-%dT%H:%M") + смещение_с_двоеточием


