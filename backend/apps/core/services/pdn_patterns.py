"""Общие шаблоны персональных данных (план 007, «Модель данных» → «Ядро и прежние модули»).

`EMAIL` и `PHONE` вынесены из `knowledge/services/pdn.py` без изменения выражений; модули, которым нужно искать и
скрывать персональные данные, берут шаблоны отсюда.
"""
import re

EMAIL = re.compile(r"(?<![\w.+-])[\w.+-]+@[\w-]+(?:\.[\w-]+)*\.[^\W\d_]{2,}(?![\w-])")
PHONE = re.compile(r"(?<![\d+])(?:\+7|8)[ \t\-()]*(?:\d[ \t\-()]*){9}\d(?!\d)")
