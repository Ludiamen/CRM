"""Напоминания задач (срез 009; каркас T-9203, полный расчёт — T-9211).

Сейчас — только снятие напоминаний при завершении и удалении задачи: строки удаляются, чтобы уникальность
автоматических напоминаний не мешала новой постановке. Планирование моментов, ручные и «Отложить» добавляет
T-9211.
"""
from apps.tasks.models import TaskReminder


def cancel_all(task, *, reason: str = "") -> int:
    """Снять все напоминания задачи; возвращает число удалённых строк."""
    deleted, _ = TaskReminder.objects.filter(task=task).delete()
    return deleted
